DO $$
DECLARE
  l record;
  s record;
  r_l real;
  moved boolean;
BEGIN
  FOR l IN
    SELECT id, x, z, max_w, max_d FROM public.city_lots
    WHERE map = 'sf' AND (x - 833) ^ 2 + (z - 1393) ^ 2 < 110 ^ 2
    ORDER BY (x - 833) ^ 2 + (z - 1393) ^ 2
  LOOP
    r_l := greatest(l.max_w, l.max_d) / 2.0 + 3;
    moved := false;
    FOR s IN
      SELECT x, z FROM landmark_spots
      WHERE sqrt((x - 833) ^ 2 + (z - 1393) ^ 2) >= 110 + r_l
      ORDER BY (x - l.x) ^ 2 + (z - l.z) ^ 2
    LOOP
      IF NOT EXISTS (
        SELECT 1 FROM public.city_lots o
        WHERE o.map = 'sf' AND o.id <> l.id
          AND o.x BETWEEN s.x - 150 AND s.x + 150 AND o.z BETWEEN s.z - 150 AND s.z + 150
          AND sqrt((o.x - s.x) ^ 2 + (o.z - s.z) ^ 2) < greatest(o.max_w, o.max_d) / 2.0 + 3 + r_l
      ) THEN
        UPDATE public.city_lots SET x = s.x, z = s.z, ring = sqrt(s.x ^ 2 + s.z ^ 2) WHERE id = l.id;
        moved := true;
        EXIT;
      END IF;
    END LOOP;
    IF NOT moved THEN
      RAISE EXCEPTION 'no free spot for lot %', l.id;
    END IF;
  END LOOP;
END $$;

